            ostatok = max(0, VREMYA_NA_VOPROS - int(proshlo))

            # Прогресс-бар времени
            st.progress(ostatok / VREMYA_NA_VOPROS, text=f"⏱ Осталось: {ostatok} сек")

            # Если время вышло
            if ostatok <= 0:
                st.session_state.igra_ishod = "vremya"
                st.session_state.igra_lives -= 1
                st.session_state.igra_combo = 0
                st.rerun()
