    # ============ ЭКРАН СТАРТА ============
    if not st.session_state.igra_started:
        st.markdown("### 🎯 Правила игры")
        st.write("- 10 вопросов, по 10 секунд на каждый")
        st.write("- 3 жизни ❤️❤️❤️ — ошибся или не успел = минус жизнь")
        st.write("- Комбо: 3 подряд — ×2 очков, 5 подряд — ×3 очков")
        st.write("- В конце — твой уровень: Стажёр / Юрист / Senior / АЮП-Мастер")

        if st.button("🚀 Начать игру", use_container_width=True):
            st.session_state.igra_started = True
